"""
PDF & Markdown Investigation Forensic Report Generator
Generates verifiable, tamper-evident investigation summaries.
Quantum Kavacha Platform
"""
import io
from typing import Dict, Any, Optional
from datetime import datetime


def generate_markdown_report(case_data: Dict[str, Any]) -> str:
    """Generates an auditable markdown forensic report."""
    case_id = case_data.get("case_id", "UNKNOWN")
    created_at = case_data.get("created_at", datetime.utcnow().isoformat())
    evidence_type = case_data.get("evidence_type", "UNKNOWN")
    final_verdict = case_data.get("final_verdict", "INCONCLUSIVE")
    risk_score = case_data.get("risk_score", "N/A")
    payment_status = case_data.get("payment_status", "NOT_APPLICABLE")
    summary = case_data.get("summary", "")
    findings = case_data.get("evidence_findings", [])
    limitations = case_data.get("limitations", [])
    recommended_actions = case_data.get("recommended_actions", [])
    extracted = case_data.get("extracted_entities", {})

    report = f"""# QUANTUM KAVACHA — FORENSIC INVESTIGATION REPORT
**Platform:** Quantum Kavacha Enterprise v2.0
**Case ID:** {case_id}
**Timestamp (UTC):** {created_at}

---

## 1. EXECUTIVE VERDICT
- **Final Security Assessment:** `{final_verdict}`
- **Calculated Risk Score:** `{risk_score} / 100`
- **Evidence Classification:** `{evidence_type}`
- **Payment Settlement Verification:** `{payment_status}`

**Executive Summary:**  
{summary}

---

## 2. EXTRACTED ARTIFACTS & ENTITIES
"""
    if extracted:
        for k, v in extracted.items():
            if v:
                report += f"- **{k.replace('_', ' ').capitalize()}:** `{v}`\n"
    else:
        report += "_No structured entity fields extracted._\n"

    report += "\n---\n\n## 3. EVIDENCE FINDINGS & DETECTOR OBSERVATIONS\n"
    if findings:
        for idx, f in enumerate(findings, 1):
            report += f"""### Finding {idx}: {f.get('title', 'Untitled')}
- **Severity:** `{f.get('severity')}`
- **Category:** `{f.get('category')}`
- **Detector:** `{f.get('detector')}`
- **Description:** {f.get('description')}
"""
            if f.get("evidence_excerpt"):
                report += f"- **Evidence Excerpt:** `{f.get('evidence_excerpt')}`\n"
            report += "\n"
    else:
        report += "_No adverse threat indicators or tampering anomalies identified._\n"

    report += "\n---\n\n## 4. RECOMMENDED ACTIONS\n"
    for act in recommended_actions:
        report += f"- {act}\n"

    report += "\n---\n\n## 5. PLATFORM LIMITATIONS & AUDIT BOUNDARIES\n"
    for lim in limitations:
        report += f"- {lim}\n"

    report += f"""
---
*Confidential Forensic Report generated by Quantum Kavacha Platform on {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}. Unauthorized distribution is prohibited.*
"""
    return report
